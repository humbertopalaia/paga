using Paga.Domain.Enums;

namespace Paga.Domain.Entities;

/// <summary>
/// A money outflow entry, optionally recurring, classified by an expense type.
/// </summary>
public class Expense
{
    public int Id { get; private set; }
    public Guid UserId { get; private set; }
    public DateOnly DueDate { get; private set; }
    public string Description { get; private set; }
    public int ExpenseTypeId { get; private set; }
    public decimal Value { get; private set; }
    public bool IsRecurring { get; private set; }
    public RecurrenceFrequency? Frequency { get; private set; }

    /// <summary>Nullable FK referencing the original recurring expense that generated this entry.</summary>
    public int? SourceEntryId { get; private set; }

    /// <summary>Whether this entry was automatically generated by the recurrence service.</summary>
    public bool IsGenerated { get; private set; }

    /// <summary>
    /// Tracks the last date for which a recurring generation was produced.
    /// Used to advance the generator past deleted entries (Requirement 3.3).
    /// </summary>
    public DateOnly? LastGeneratedDate { get; private set; }

    /// <summary>Self-referential navigation to the source recurring expense.</summary>
    public Expense? SourceEntry { get; private set; }

    public Expense(Guid userId, DateOnly dueDate, string description, int expenseTypeId, decimal value, bool isRecurring, RecurrenceFrequency? frequency)
    {
        UserId = userId;
        DueDate = dueDate;
        Description = description;
        ExpenseTypeId = expenseTypeId;
        Value = value;
        IsRecurring = isRecurring;
        Frequency = frequency;
        IsGenerated = false;
    }

    /// <summary>
    /// Creates a generated expense entry linked to the specified source.
    /// </summary>
    /// <param name="source">The recurring source expense this entry is generated from.</param>
    /// <param name="dueDate">The computed due date for the generated entry.</param>
    /// <returns>A new <see cref="Expense"/> with <see cref="IsGenerated"/> set to <c>true</c>.</returns>
    public static Expense CreateGenerated(Expense source, DateOnly dueDate)
    {
        return new Expense(source.UserId, dueDate, source.Description, source.ExpenseTypeId, source.Value, source.IsRecurring, source.Frequency)
        {
            SourceEntryId = source.Id,
            IsGenerated = true
        };
    }

    /// <summary>
    /// Updates all mutable fields for controlled mutation.
    /// </summary>
    public void Update(DateOnly dueDate, string description, int expenseTypeId, decimal value, bool isRecurring, RecurrenceFrequency? frequency)
    {
        DueDate = dueDate;
        Description = description;
        ExpenseTypeId = expenseTypeId;
        Value = value;
        IsRecurring = isRecurring;
        Frequency = frequency;
    }

    /// <summary>
    /// Clears the source entry reference, orphaning this generated entry.
    /// </summary>
    public void ClearSourceEntry()
    {
        SourceEntryId = null;
    }

    /// <summary>
    /// Advances the last generated date tracker. The generator uses this to avoid
    /// recreating entries for periods that were already generated (even if later deleted).
    /// </summary>
    /// <param name="date">The date of the most recently generated entry.</param>
    public void SetLastGeneratedDate(DateOnly date)
    {
        LastGeneratedDate = date;
    }

    // EF Core requires a parameterless constructor; kept private to enforce invariants.
    private Expense()
    {
        Description = string.Empty;
    }
}
