using Paga.Domain.Enums;

namespace Paga.Domain.Entities;

/// <summary>
/// A money inflow entry, optionally recurring.
/// </summary>
public class Income
{
    public int Id { get; private set; }
    public Guid UserId { get; private set; }
    public DateOnly Date { get; private set; }
    public string Description { get; private set; }
    public decimal Value { get; private set; }
    public bool IsRecurring { get; private set; }
    public RecurrenceFrequency? Frequency { get; private set; }

    /// <summary>
    /// Nullable FK referencing the original recurring income that generated this entry.
    /// Null for manually created entries.
    /// </summary>
    public int? SourceEntryId { get; private set; }

    /// <summary>
    /// Whether this entry was automatically generated by the recurrence service.
    /// </summary>
    public bool IsGenerated { get; private set; }

    /// <summary>
    /// Tracks the last date for which a recurring generation was produced.
    /// Used to advance the generator past deleted entries (Requirement 3.3).
    /// </summary>
    public DateOnly? LastGeneratedDate { get; private set; }

    /// <summary>
    /// Self-referential navigation to the source recurring income (for EF convenience).
    /// </summary>
    public Income? SourceEntry { get; private set; }

    public Income(Guid userId, DateOnly date, string description, decimal value, bool isRecurring, RecurrenceFrequency? frequency)
    {
        UserId = userId;
        Date = date;
        Description = description;
        Value = value;
        IsRecurring = isRecurring;
        Frequency = frequency;
        IsGenerated = false;
        SourceEntryId = null;
    }

    /// <summary>
    /// Creates a generated income entry linked to the specified source.
    /// </summary>
    /// <param name="source">The recurring source income this entry is generated from.</param>
    /// <param name="date">The computed date for the generated entry.</param>
    /// <returns>A new <see cref="Income"/> marked as generated with the source linkage.</returns>
    public static Income CreateGenerated(Income source, DateOnly date)
    {
        return new Income(source.UserId, date, source.Description, source.Value, source.IsRecurring, source.Frequency)
        {
            IsGenerated = true,
            SourceEntryId = source.Id
        };
    }

    /// <summary>
    /// Updates all mutable fields for controlled mutation.
    /// </summary>
    /// <param name="date">The new date for this income.</param>
    /// <param name="description">The new description.</param>
    /// <param name="value">The new monetary value.</param>
    /// <param name="isRecurring">Whether this income recurs.</param>
    /// <param name="frequency">The recurrence frequency (required when recurring, null otherwise).</param>
    public void Update(DateOnly date, string description, decimal value, bool isRecurring, RecurrenceFrequency? frequency)
    {
        Date = date;
        Description = description;
        Value = value;
        IsRecurring = isRecurring;
        Frequency = frequency;
    }

    /// <summary>
    /// Clears the source entry reference, orphaning this generated entry.
    /// </summary>
    public void ClearSourceEntry()
    {
        SourceEntryId = null;
    }

    /// <summary>
    /// Advances the last generated date tracker. The generator uses this to avoid
    /// recreating entries for periods that were already generated (even if later deleted).
    /// </summary>
    /// <param name="date">The date of the most recently generated entry.</param>
    public void SetLastGeneratedDate(DateOnly date)
    {
        LastGeneratedDate = date;
    }

    // EF Core requires a parameterless constructor; kept private to enforce invariants.
    private Income()
    {
        Description = string.Empty;
    }
}
